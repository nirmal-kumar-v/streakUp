import { describe, it, expect } from 'vitest';
import { areFriends } from '../src/controllers/friendTaskController';

describe('Privacy & Authorization Enforcement', () => {
  it('identifies self as authorized', async () => {
    const isOwner = await areFriends('user-1', 'user-1');
    expect(isOwner).toBe(true);
  });

  it('filters sensitive fields from public leaderboard payloads', () => {
    // Simulated raw user object from DB
    const rawDbUser = {
      id: 'u-1',
      name: 'Alice',
      username: 'alice',
      passwordHash: 'secret_hash_value',
      email: 'alice@example.com',
      currentStreak: 5,
      longestStreak: 12,
      profileImage: null,
      overallFreezeBalance: 1,
      overallFreezeRechargeDays: 3,
      tasks: [
        { id: 't-1', title: 'Private Task', studyNote: 'Private Note' }
      ]
    };

    // Public representation as generated by getGlobalLeaderboard
    const publicUser = {
      id: rawDbUser.id,
      name: rawDbUser.name,
      username: rawDbUser.username,
      profileImage: rawDbUser.profileImage,
      currentStreak: rawDbUser.currentStreak,
      longestStreak: rawDbUser.longestStreak
    };

    expect((publicUser as any).passwordHash).toBeUndefined();
    expect((publicUser as any).email).toBeUndefined();
    expect((publicUser as any).overallFreezeBalance).toBeUndefined();
    expect((publicUser as any).tasks).toBeUndefined();
    expect((publicUser as any).studyNote).toBeUndefined();
  });

  it('validates image upload size limit (rejects files > 5MB)', () => {
    const MAX_SIZE_BYTES = 5 * 1024 * 1024;
    const oversizedBytes = 6 * 1024 * 1024;
    expect(oversizedBytes > MAX_SIZE_BYTES).toBe(true);
  });

  it('validates supported image mime types (JPEG, PNG, WebP only)', () => {
    const allowed = ['image/jpeg', 'image/jpg', 'image/png', 'image/webp'];
    const validJpg = 'data:image/jpeg;base64,abc';
    const validPng = 'data:image/png;base64,abc';
    const validWebp = 'data:image/webp;base64,abc';
    const invalidGif = 'data:image/gif;base64,abc';
    const invalidSvg = 'data:image/svg+xml;base64,abc';

    const testMime = (uri: string) => {
      const match = uri.match(/^data:(image\/[a-zA-Z0-9+.-]+);base64,/i);
      return match ? allowed.includes(match[1].toLowerCase()) : false;
    };

    expect(testMime(validJpg)).toBe(true);
    expect(testMime(validPng)).toBe(true);
    expect(testMime(validWebp)).toBe(true);
    expect(testMime(invalidGif)).toBe(false);
    expect(testMime(invalidSvg)).toBe(false);
  });

  it('enforces 14-day username change rate limit', () => {
    const now = new Date('2026-10-15T12:00:00Z');
    const changed5DaysAgo = new Date('2026-10-10T12:00:00Z');
    const changed15DaysAgo = new Date('2026-09-30T12:00:00Z');

    const canChange = (lastDate: Date) => {
      const diffMs = now.getTime() - lastDate.getTime();
      const diffDays = diffMs / (1000 * 60 * 60 * 24);
      return diffDays >= 14;
    };

    expect(canChange(changed5DaysAgo)).toBe(false);
    expect(canChange(changed15DaysAgo)).toBe(true);
  });

  describe('Authorization Rules Matrix', () => {
    // Model for authorization check
    type FriendStatus = 'NONE' | 'PENDING' | 'ACCEPTED' | 'REJECTED';

    const checkCanAccessFriendsOnlyData = (
      requesterId: string | null,
      resourceOwnerId: string,
      friendshipStatus: FriendStatus
    ): boolean => {
      // 1. Logged out visitor
      if (!requesterId) return false;
      // 2. Resource owner (always allowed)
      if (requesterId === resourceOwnerId) return true;
      // 3. Accepted friend only
      return friendshipStatus === 'ACCEPTED';
    };

    it('denies access to logged-out users for friends-only task data', () => {
      expect(checkCanAccessFriendsOnlyData(null, 'user-A', 'ACCEPTED')).toBe(false);
    });

    it('denies access to strangers with no relationship', () => {
      expect(checkCanAccessFriendsOnlyData('stranger-1', 'user-A', 'NONE')).toBe(false);
    });

    it('denies access to users with pending friend requests', () => {
      expect(checkCanAccessFriendsOnlyData('pending-user', 'user-A', 'PENDING')).toBe(false);
    });

    it('denies access to rejected friend requests', () => {
      expect(checkCanAccessFriendsOnlyData('rejected-user', 'user-A', 'REJECTED')).toBe(false);
    });

    it('allows access to accepted friends', () => {
      expect(checkCanAccessFriendsOnlyData('friend-1', 'user-A', 'ACCEPTED')).toBe(true);
    });

    it('allows access to the resource owner', () => {
      expect(checkCanAccessFriendsOnlyData('user-A', 'user-A', 'NONE')).toBe(true);
    });

    it('revokes access immediately when friendship is removed', () => {
      let status: FriendStatus = 'ACCEPTED';
      expect(checkCanAccessFriendsOnlyData('friend-1', 'user-A', status)).toBe(true);

      // Friend is removed
      status = 'NONE';
      expect(checkCanAccessFriendsOnlyData('friend-1', 'user-A', status)).toBe(false);
    });
  });

  describe('Study Note Isolation & Mutation Rules', () => {
    it('associates study notes with individual completion records, not permanently to task', () => {
      const completions = [
        { id: 'c-1', taskId: 't-1', date: '2026-10-12', studyNote: 'Studied MCQs' },
        { id: 'c-2', taskId: 't-1', date: '2026-10-13', studyNote: 'Solved sliding window' },
        { id: 'c-3', taskId: 't-1', date: '2026-10-14', studyNote: null },
      ];

      expect(completions[0].studyNote).toBe('Studied MCQs');
      expect(completions[1].studyNote).toBe('Solved sliding window');
      expect(completions[2].studyNote).toBeNull();
    });

    it('editing a study note updates note content without creating duplicate completions or increasing streak', () => {
      const completion = {
        id: 'c-1',
        taskId: 't-1',
        date: '2026-10-12',
        studyNote: 'Original note',
        createdAt: new Date('2026-10-12T10:00:00Z'),
      };

      // Edit note
      const updatedNote = 'Revised note with TCP congestion control';
      const updatedCompletion = {
        ...completion,
        studyNote: updatedNote,
      };

      // Ensure completion ID and date are identical
      expect(updatedCompletion.id).toBe(completion.id);
      expect(updatedCompletion.date).toBe(completion.date);
      expect(updatedCompletion.studyNote).toBe('Revised note with TCP congestion control');
    });

    it('undoing a completion removes it from active list and does not show withdrawn note', () => {
      let completions = [
        { id: 'c-1', date: '2026-10-12', studyNote: 'Studied process sync' }
      ];

      // Untick/undo
      completions = completions.filter(c => c.id !== 'c-1');
      expect(completions.length).toBe(0);
      expect(completions.find(c => c.id === 'c-1')).toBeUndefined();
    });
  });
});
